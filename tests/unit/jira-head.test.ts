import { describe, expect, it } from 'vitest'
import { JiraHead, jiraCommentIntent, jiraConfirm, jiraListError, jiraListing, jiraMenu, jiraResult, jiraSending, jiraTransitionIntent, jiraTransitionLabel, type JiraHeadApi } from '../../src/shared/jira-head'
import type { JiraTransition, JiraWriteState, JiraWriteStatus } from '../../src/shared/jira-write'

// 일감 머리의 Jira 쓰기 판단 — main · Jira 없이, 답을 손으로 늦춰(gate) 순서를 뒤집어 본다.
interface Gate<T> { args: unknown; resolve(value: T): void; reject(reason: Error): void }
function gated() {
  const calls = { transitions: [] as Gate<JiraTransition[]>[], transition: [] as Gate<JiraWriteState>[], comment: [] as Gate<JiraWriteState>[], writeState: [] as Gate<JiraWriteState | null>[], refresh: [] as Gate<unknown>[] }
  const hold = <T,>(list: Gate<T>[]) => (args: unknown) => new Promise<T>((resolve, reject) => { list.push({ args, resolve, reject }) })
  const api: JiraHeadApi = { transitions: hold(calls.transitions), transition: hold(calls.transition), comment: hold(calls.comment), writeState: hold(calls.writeState), refresh: hold(calls.refresh) }
  let refreshed = 0
  const head = new JiraHead(api, 'task-1', () => { refreshed++ })
  return { calls, head, refreshed: () => refreshed }
}
const tick = async () => { for (let i = 0; i < 5; i++) await Promise.resolve() }
const DONE: JiraTransition = { id: '31', name: 'Done', to: { id: '30', name: 'Done', category: 'done' } }
const START: JiraTransition = { id: '21', name: '진행 시작', to: { id: '20', name: 'In Progress', category: 'indeterminate' } }
const state = (requestId: string, status: JiraWriteStatus, message = '', kind: 'transition' | 'comment' = 'transition'): JiraWriteState => ({ requestId, kind, key: 'PROJ-7', status, message })
const move = (requestId = 'req-1', key = 'PROJ-7') => jiraTransitionIntent(requestId, key, 'To Do', DONE)

describe('Jira 일감 머리 — 전환 목록 읽기', () => {
  it('메뉴를 열 때만 읽고, 늦게 온 옛 답은 새 답을 덮지 않는다', async () => {
    const { calls, head } = gated()
    expect(calls.transitions).toHaveLength(0)
    void head.openMenu('PROJ-7')
    expect(jiraListing(head.view, 'PROJ-7')).toBe(true)
    // 그 사이 연결이 PROJ-8 로 바뀌어 다시 눌렀다
    void head.openMenu('PROJ-8')
    calls.transitions[1]!.resolve([START])
    await tick()
    calls.transitions[0]!.resolve([DONE])
    await tick()
    expect(calls.transitions.map((c) => c.args)).toEqual(['PROJ-7', 'PROJ-8'])
    expect(jiraMenu(head.view, 'PROJ-8')).toEqual([START])
    // 다른 이슈의 목록은 지금 연결의 메뉴로 보이지 않는다
    expect(jiraMenu(head.view, 'PROJ-7')).toBeNull()
    expect(jiraListing(head.view, 'PROJ-8')).toBe(false)
  })
  it('읽는 중 다시 눌러도 요청은 하나 · 실패는 그 이슈에만 글로 보이고 닫으면 늦은 답을 버린다', async () => {
    const { calls, head } = gated()
    void head.openMenu('PROJ-7'); void head.openMenu('PROJ-7')
    expect(calls.transitions).toHaveLength(1)
    calls.transitions[0]!.reject(new Error("Error invoking remote method 'jira:transitions': Error: [jira] 권한이 없어요(403)."))
    await tick()
    expect(jiraListError(head.view, 'PROJ-7')).toBe('권한이 없어요(403).')
    expect(jiraListError(head.view, 'PROJ-8')).toBe('')
    void head.openMenu('PROJ-7')
    expect(jiraListError(head.view, 'PROJ-7')).toBe('')
    head.closeMenu()
    calls.transitions[1]!.resolve([DONE])
    await tick()
    expect(jiraMenu(head.view, 'PROJ-7')).toBeNull()
    expect(jiraListing(head.view, 'PROJ-7')).toBe(false)
  })
  it('메뉴 줄 · 확인 글 — 현재 상태 → 바꿀 상태와 이슈 키, 댓글은 글의 앞부분', () => {
    expect(jiraTransitionLabel(DONE)).toBe('Done')
    expect(jiraTransitionLabel(START)).toBe('진행 시작 → In Progress')
    expect(jiraConfirm(move())).toEqual({ title: 'Jira 상태 바꾸기', message: 'PROJ-7\nTo Do → Done', confirmLabel: '상태 바꾸기' })
    const long = jiraConfirm(jiraCommentIntent('req-c', 'PROJ-7', '가'.repeat(500)))
    expect(long.title).toBe('Jira 댓글 남기기')
    expect(long.message.startsWith('PROJ-7\n')).toBe(true)
    expect(long.message.length).toBeLessThan(260)
    expect(long.message.endsWith('…')).toBe(true)
    expect(jiraConfirm(jiraCommentIntent('req-c', 'PROJ-7', '짧은 글')).message).toBe('PROJ-7\n짧은 글')
  })
})

describe('Jira 일감 머리 — 확인 뒤 보내기', () => {
  it('떠 둔 키 · 전환 · 번호로 보내고, 보내는 중에는 두 단추를 막고 두 번 눌러도 한 번', async () => {
    const { calls, head } = gated()
    const intent = move()
    void head.send(intent); void head.send(intent); void head.send(jiraCommentIntent('req-2', 'PROJ-7', '글'))
    expect(calls.transition.map((c) => c.args)).toEqual([{ key: 'PROJ-7', transitionId: '31', requestId: 'req-1' }])
    expect(calls.comment).toHaveLength(0)
    expect(jiraSending(head.view, 'PROJ-7')).toBe(true)
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '보내는 중…', tone: 'status', actions: [] })
    // 보내는 중에는 메뉴도 열지 않는다
    void head.openMenu('PROJ-7')
    expect(calls.transitions).toHaveLength(0)
    calls.transition[0]!.resolve(state('req-1', 'done'))
    await tick()
    expect(jiraSending(head.view, 'PROJ-7')).toBe(false)
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: '바꿨어요', tone: 'status' })
  })
  it('떠 둔 키와 지금 연결이 다르면 결과를 보이지 않고 새 이슈의 단추도 막지 않는다 — 새 이슈에는 쓰지 않는다', async () => {
    const { calls, head } = gated()
    // 확인 창을 연 순간 PROJ-7 을 떠 뒀고, 확인을 누르기 전에 연결이 PROJ-8 로 바뀌었다
    void head.send(move('req-1', 'PROJ-7'))
    expect(calls.transition[0]!.args).toMatchObject({ key: 'PROJ-7' })
    expect(jiraSending(head.view, 'PROJ-8')).toBe(false)
    expect(jiraResult(head.view, 'PROJ-8')).toBeNull()
    calls.transition[0]!.resolve(state('req-1', 'failed', '권한이 없어요(403).'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-8')).toBeNull()
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '안 됐어요: 권한이 없어요(403).', tone: 'alert', actions: [] })
  })
  it('더 새 쓰기가 시작된 뒤 늦게 온 옛 쓰기 답은 칸을 덮지 않는다', async () => {
    const { calls, head } = gated()
    void head.send(move('req-1', 'PROJ-7'))
    void head.send(jiraCommentIntent('req-2', 'PROJ-8', '새 이슈의 글'))
    calls.comment[0]!.resolve(state('req-2', 'done', '', 'comment'))
    await tick()
    calls.transition[0]!.resolve(state('req-1', 'failed', '옛 답'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-8')).toMatchObject({ text: '댓글을 남겼어요' })
    expect(jiraResult(head.view, 'PROJ-7')).toBeNull()
  })
  it('됐는지 모름 — 다시 확인은 같은 번호 · 같은 내용으로 부르고 자동으로는 다시 보내지 않는다', async () => {
    const { calls, head } = gated()
    void head.send(move())
    calls.transition[0]!.resolve(state('req-1', 'unknown', '응답이 중간에 끊겼어요.'))
    await tick(); await tick()
    expect(calls.transition).toHaveLength(1)
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '됐는지 모름 — 응답이 중간에 끊겼어요.', tone: 'alert', actions: [{ kind: 'write', label: '다시 확인' }] })
    expect(jiraSending(head.view, 'PROJ-7')).toBe(false)
    void head.retry()
    expect(calls.transition[1]!.args).toEqual(calls.transition[0]!.args)
    expect(jiraSending(head.view, 'PROJ-7')).toBe(true)
    calls.transition[1]!.resolve(state('req-1', 'done'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: '바꿨어요' })
    // 됨 · 안 됨에서는 다시 확인이 아무것도 부르지 않는다
    void head.retry()
    expect(calls.transition).toHaveLength(2)
  })
  it('main 이 [jira] 글로 거절하면 안 됨 — 다시 확인 중의 거절과 그 밖의 오류는 여전히 모름', async () => {
    const { calls, head } = gated()
    void head.send(move())
    calls.transition[0]!.reject(new Error("Error invoking remote method 'jira:transition': Error: [jira] 전환 목록을 다시 읽은 뒤 골라 주세요."))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '안 됐어요: 전환 목록을 다시 읽은 뒤 골라 주세요.', tone: 'alert', actions: [] })
    void head.send(move('req-2'))
    calls.transition[1]!.reject(new Error('reply was never sent'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: expect.stringContaining('됐는지 모름'), actions: [{ kind: 'write' }] })
    void head.retry()
    calls.transition[2]!.reject(new Error('Error: [jira] Jira 인증이 바뀌어 이 요청은 이어서 확인할 수 없어요.'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: '됐는지 모름 — Jira 인증이 바뀌어 이 요청은 이어서 확인할 수 없어요.' })
  })
  it('댓글 — 입력 중인 글은 보내기에 성공할 때까지 지우지 않는다', async () => {
    const { calls, head } = gated()
    head.compose(true)
    head.setDraft('확인했어요')
    void head.send(jiraCommentIntent('req-1', 'PROJ-7', head.view.draft))
    expect(calls.comment[0]!.args).toEqual({ key: 'PROJ-7', text: '확인했어요', requestId: 'req-1' })
    calls.comment[0]!.resolve(state('req-1', 'unknown', '응답이 없어요.', 'comment'))
    await tick()
    expect(head.view).toMatchObject({ draft: '확인했어요', composing: true })
    void head.retry()
    calls.comment[1]!.resolve(state('req-1', 'failed', '권한이 없어요(403).', 'comment'))
    await tick()
    expect(head.view).toMatchObject({ draft: '확인했어요', composing: true })
    void head.send(jiraCommentIntent('req-2', 'PROJ-7', head.view.draft))
    calls.comment[2]!.resolve(state('req-2', 'done', '', 'comment'))
    await tick()
    expect(head.view).toMatchObject({ draft: '', composing: false })
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '댓글을 남겼어요', tone: 'status', actions: [] })
    // 보내는 사이 고쳐 쓴 글은 성공해도 남긴다
    head.compose(true); head.setDraft('둘째 글')
    void head.send(jiraCommentIntent('req-3', 'PROJ-7', '둘째 글'))
    head.setDraft('둘째 글에 덧붙임')
    calls.comment[3]!.resolve(state('req-3', 'done', '', 'comment'))
    await tick()
    expect(head.view).toMatchObject({ draft: '둘째 글에 덧붙임', composing: true })
  })
})

describe('Jira 일감 머리 — 전환 뒤 상태 다시 읽기 · 돌아옴', () => {
  it('전환이 끝나면 상태를 다시 읽는다 — 앞 읽기가 도는 중이어도 건너뛰지 않고, 늦게 온 앞 답은 버린다', async () => {
    const { calls, head, refreshed } = gated()
    void head.send(move('req-1'))
    calls.transition[0]!.resolve(state('req-1', 'done'))
    await tick()
    expect(calls.refresh.map((c) => c.args)).toEqual([{ taskId: 'task-1', key: 'PROJ-7' }])
    // 첫 읽기가 도는 중에 둘째 전환이 끝났다
    void head.send(jiraTransitionIntent('req-2', 'PROJ-7', 'Done', START))
    calls.transition[1]!.resolve(state('req-2', 'done'))
    await tick()
    expect(calls.refresh).toHaveLength(2)
    calls.refresh[1]!.resolve(null)
    await tick()
    expect(refreshed()).toBe(1)
    // 둘째 전환 앞의 상태를 읽은 옛 답 — 실패든 성공이든 지금 상태를 덮지 않는다
    calls.refresh[0]!.reject(new Error('옛 읽기 실패'))
    await tick()
    expect(head.view.reread).toBeNull()
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '바꿨어요', tone: 'status', actions: [] })
    expect(refreshed()).toBe(1)
  })
  it('전환은 됐는데 상태 다시 읽기만 실패하면 그렇게 보이고, 다시 시도는 읽기만 한다', async () => {
    const { calls, head, refreshed } = gated()
    void head.send(move())
    calls.transition[0]!.resolve(state('req-1', 'done'))
    await tick()
    calls.refresh[0]!.reject(new Error('[jira] 응답이 없어요.'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '바꿨어요 · 상태를 다시 읽지 못했어요', tone: 'alert', actions: [{ kind: 'read', label: '상태 다시 읽기' }] })
    expect(jiraResult(head.view, 'PROJ-8')).toBeNull()
    void head.rereadState()
    expect(calls.refresh).toHaveLength(2)
    expect(calls.transition).toHaveLength(1)
    calls.refresh[1]!.resolve(null)
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: '바꿨어요', actions: [] })
    expect(refreshed()).toBe(1)
    // 댓글 뒤에는 상태를 읽지 않는다
    void head.send(jiraCommentIntent('req-2', 'PROJ-7', '글'))
    calls.comment[0]!.resolve(state('req-2', 'done', '', 'comment'))
    await tick()
    expect(calls.refresh).toHaveLength(2)
  })
  it('돌아오면 writeState 로 보내는 중이던 쓰기의 결과를 다시 보인다 — 한 번에 하나만 묻는다', async () => {
    const { calls, head } = gated()
    void head.resume()
    expect(calls.writeState).toHaveLength(0)
    void head.send(move())
    void head.resume(); void head.resume()
    expect(calls.writeState.map((c) => c.args)).toEqual(['req-1'])
    calls.writeState[0]!.resolve(state('req-1', 'pending'))
    await tick()
    expect(jiraSending(head.view, 'PROJ-7')).toBe(true)
    void head.resume()
    calls.writeState[1]!.resolve(state('req-1', 'done'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: '바꿨어요' })
    expect(calls.refresh).toHaveLength(1)
    // 뒤늦게 끝난 원래 호출의 답은 같은 결과를 두 번 처리하지 않는다
    calls.transition[0]!.resolve(state('req-1', 'done'))
    await tick()
    expect(calls.refresh).toHaveLength(1)
    void head.resume()
    expect(calls.writeState).toHaveLength(2)
  })
  it('늦게 온 writeState 답은 그 사이 정해진 더 새 상태를 덮지 않는다', async () => {
    const { calls, head } = gated()
    void head.send(move())
    void head.resume()
    calls.transition[0]!.resolve(state('req-1', 'unknown', '응답이 없어요.'))
    await tick()
    void head.retry()
    // 다시 확인이 도는 중에, 그 앞에 물었던 답(모름)이 늦게 왔다
    calls.writeState[0]!.resolve(state('req-1', 'unknown', '옛 답'))
    await tick()
    expect(jiraSending(head.view, 'PROJ-7')).toBe(true)
    calls.transition[1]!.resolve(state('req-1', 'done'))
    await tick()
    expect(jiraResult(head.view, 'PROJ-7')).toMatchObject({ text: '바꿨어요' })
    // main 의 기록에 없다는 답(null) · 묻기 실패는 화면을 바꾸지 않는다
    void head.send(move('req-2'))
    void head.resume()
    calls.writeState[1]!.resolve(null)
    await tick()
    expect(jiraSending(head.view, 'PROJ-7')).toBe(true)
  })
  it('새로 고르기 시작하면 끝난 결과 줄은 치우고, 됐는지 모름은 남긴다', async () => {
    const { calls, head } = gated()
    void head.send(move())
    calls.transition[0]!.resolve(state('req-1', 'failed', '거절'))
    await tick()
    void head.openMenu('PROJ-7')
    expect(jiraResult(head.view, 'PROJ-7')).toBeNull()
    head.closeMenu()
    void head.send(move('req-2'))
    calls.transition[1]!.resolve(state('req-2', 'unknown', ''))
    await tick()
    void head.openMenu('PROJ-7')
    head.compose(true)
    expect(jiraResult(head.view, 'PROJ-7')).toEqual({ text: '됐는지 모름', tone: 'alert', actions: [{ kind: 'write', label: '다시 확인' }] })
  })
})
